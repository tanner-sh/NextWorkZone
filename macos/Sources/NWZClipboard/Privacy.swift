import Foundation

/// 隐私保护：不记录疑似密钥、密码的内容，默认忽略密码管理器。
public enum ClipPrivacy {
    /// 默认不记录的应用（Bundle ID, 名称）：常见的密码管理器。
    public static let defaultIgnoredApps: [(id: String, name: String)] = [
        ("com.1password.1password", "1Password"),
        ("com.agilebits.onepassword7", "1Password 7"),
        ("com.bitwarden.desktop", "Bitwarden"),
        ("org.keepassxc.keepassxc", "KeePassXC"),
        ("com.apple.keychainaccess", "钥匙串访问"),
        ("com.apple.Passwords", "密码"),
        ("com.lastpass.LastPass", "LastPass"),
        ("in.sinew.Enpass-Desktop", "Enpass"),
    ]

    /// 写入方用来标记“不要记录”的剪贴板类型（nspasteboard.org 约定，以及几款常见应用的私有类型）。
    public static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    /// 常见服务的令牌、私钥格式（公开的前缀规则）。
    nonisolated(unsafe) private static let secretPattern = /-----BEGIN [A-Z ]*PRIVATE KEY-----|\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{36}\b|\bgithub_pat_[A-Za-z0-9_]{60,}|\bglpat-[A-Za-z0-9_\-]{20,}|\bxox[abposr]-[A-Za-z0-9\-]{10,}|\bAKIA[0-9A-Z]{16}\b|\bAIza[0-9A-Za-z_\-]{35}\b|\bsk-(?:proj-|ant-)?[A-Za-z0-9_\-]{32,}/

    /// 内容疑似密钥或密码：包含已知格式的令牌、私钥，或是一段像随机密码的短文字。
    public static func looksSecret(_ text: String) -> Bool {
        text.contains(secretPattern) || looksLikePassword(text.trimmingCharacters(in: .whitespacesAndNewlines))
    }

    /// 8–64 个字符、没有空白、同时包含大写字母、小写字母、数字和符号，且不像地址、路径或邮箱。
    private static func looksLikePassword(_ text: String) -> Bool {
        guard (8...64).contains(text.count), text.unicodeScalars.allSatisfy({ $0.isASCII && !$0.properties.isWhitespace }) else { return false }
        if text.contains("://") || text.hasPrefix("/") || text.hasPrefix("~") || text.contains("\\") || text.contains("@") && text.contains(".") { return false }
        let scalars = text.unicodeScalars
        let upper = scalars.contains { ("A"..."Z").contains($0) }
        let lower = scalars.contains { ("a"..."z").contains($0) }
        let digit = scalars.contains { ("0"..."9").contains($0) }
        // ASCII 标点中去掉常出现在标识符、文件名里的 _ - .
        let symbol = scalars.contains { "!\"#$%&'()*+,/:;<=>?@[\\]^`{|}~".unicodeScalars.contains($0) }
        return upper && lower && digit && symbol
    }

    /// 是否不记录这个应用中复制的内容：内置的密码管理器，或用户添加的忽略应用。
    public static func ignored(_ appID: String, extra: [String]) -> Bool {
        defaultIgnoredApps.contains { $0.id.caseInsensitiveCompare(appID) == .orderedSame } || extra.contains { $0.caseInsensitiveCompare(appID) == .orderedSame }
    }
}
